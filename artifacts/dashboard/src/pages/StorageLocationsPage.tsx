// ─── Linked Record Detail Dialog ─────────────────────────────────────────────

function LinkedRecordDetailDialog({
  farmId, linkedRecordType, linkedRecordId, onClose,
}: { farmId: number; linkedRecordType: string; linkedRecordId: number; onClose: () => void }) {
  const haulQ = useQuery<{ record: HaulageRef }>({
    queryKey: ["linked-haulage", farmId, linkedRecordId],
    queryFn: () => fetch(`/api/farms/${farmId}/haulage/${linkedRecordId}`, { credentials: "include" }).then((r) => r.json()),
    enabled: linkedRecordType === "haulage_record",
  });
  const saleQ = useQuery<{ record: GrainSaleRef }>({
    queryKey: ["linked-grain-sale", farmId, linkedRecordId],
    queryFn: () => fetch(`/api/farms/${farmId}/grain-sales/${linkedRecordId}`, { credentials: "include" }).then((r) => r.json()),
    enabled: linkedRecordType === "grain_sale",
  });
  const harvestQ = useQuery<{ record: HarvestRef }>({
    queryKey: ["linked-harvest", farmId, linkedRecordId],
    queryFn: () => fetch(`/api/farms/${farmId}/harvests/${linkedRecordId}`, { credentials: "include" }).then((r) => r.json()),
    enabled: linkedRecordType === "harvest_record",
  });

  const isLoading = haulQ.isLoading || saleQ.isLoading || harvestQ.isLoading;

  function Row({ label, value }: { label: string; value: string | number | null | undefined }) {
    return value != null && value !== "" ? (
      <div className="grid grid-cols-[120px_1fr] gap-1 py-1 border-b border-muted/40 last:border-0">
        <span className="text-xs text-muted-foreground">{label}</span>
        <span className="text-xs font-medium">{value}</span>
      </div>
    ) : null;
  }

  const recordLabel =
    linkedRecordType === "haulage_record" ? "Haulage Record" :
    linkedRecordType === "grain_sale"     ? "Grain Sale" :
    linkedRecordType === "harvest_record" ? "Harvest Record" : "Linked Record";

  const RecordIcon =
    linkedRecordType === "haulage_record" ? Truck :
    linkedRecordType === "grain_sale"     ? ShoppingCart :
    linkedRecordType === "harvest_record" ? Wheat : Link2;

  return (
    <Dialog open onOpenChange={(o) => { if (!o) onClose(); }}>
      <DialogContent style={{ maxWidth: 440 }} aria-describedby={undefined}>
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <RecordIcon className="h-4 w-4 text-muted-foreground" />
            {recordLabel}
          </DialogTitle>
        </DialogHeader>

        {isLoading && <p className="text-sm text-muted-foreground py-4 text-center">Loading…</p>}

        {linkedRecordType === "haulage_record" && haulQ.data?.record && (() => {
          const r = haulQ.data.record;
          return (
            <div className="pt-1">
              <Row label="Ticket No" value={r.weighbridgeTicketNo} />
              <Row label="Date" value={r.departureDate ? r.departureDate.slice(0, 10) : null} />
              <Row label="Movement" value={r.movementType === "farm_exit_dispatch" ? "Farm exit / dispatch" : r.movementType} />
              <Row label="Commodity" value={[r.commodity, r.variety].filter(Boolean).join(" — ") || null} />
              <Row label="Weight" value={r.weightTonnes ? `${r.weightTonnes} t` : null} />
              <Row label="Destination" value={r.destination} />
              <Row label="Vehicle" value={r.vehicleRegistration} />
              <Row label="Driver" value={r.driverName} />
              <Row label="Haulier" value={r.haulierCompany} />
              <Row label="Customer ref" value={r.customerRef} />
            </div>
          );
        })()}

        {linkedRecordType === "grain_sale" && saleQ.data?.record && (() => {
          const r = saleQ.data.record;
          const price = r.pricePerTonnePence != null ? `£${(r.pricePerTonnePence / 100).toFixed(2)}/t` : null;
          const net   = r.netValuePence      != null ? `£${(r.netValuePence      / 100).toFixed(2)}`   : null;
          return (
            <div className="pt-1">
              <Row label="Merchant ref" value={r.merchantRef} />
              <Row label="Sale date" value={r.saleDate ? r.saleDate.slice(0, 10) : null} />
              <Row label="Sale type" value={r.saleType} />
              <Row label="Buyer" value={r.buyer} />
              <Row label="Commodity" value={[r.commodity, r.variety].filter(Boolean).join(" — ") || null} />
              <Row label="Crop year" value={r.cropYear} />
              <Row label="Tonnage" value={r.tonnage ? `${r.tonnage} t` : null} />
              <Row label="Price/tonne" value={price} />
              <Row label="Net value" value={net} />
              <Row label="Invoice No" value={r.invoiceNumber} />
              <Row label="Delivery date" value={r.deliveryDate ? r.deliveryDate.slice(0, 10) : null} />
            </div>
          );
        })()}

        {linkedRecordType === "harvest_record" && harvestQ.data?.record && (() => {
          const r = harvestQ.data.record;
          return (
            <div className="pt-1">
              <Row label="Harvest date" value={r.harvestDate ? r.harvestDate.slice(0, 10) : null} />
              <Row label="Field" value={r.field?.name} />
              <Row label="Crop" value={[r.crop?.cropType, r.crop?.variety].filter(Boolean).join(" — ") || null} />
              <Row label="Yield" value={r.yieldTonnes ? `${r.yieldTonnes} t` : null} />
              <Row label="Area harvested" value={r.areaHarvestedHa ? `${r.areaHarvestedHa} ha` : null} />
              <Row label="Moisture" value={r.moisturePercent ? `${r.moisturePercent}%` : null} />
              <Row label="Grade" value={r.qualityGrade} />
            </div>
          );
        })()}

        {!isLoading && (haulQ.isError || saleQ.isError || harvestQ.isError) && (
          <p className="text-sm text-destructive py-4 text-center">Could not load record. It may belong to a different module.</p>
        )}

        <DialogFooter>
          <Button variant="outline" onClick={onClose}>Close</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

// ─── Stock Movements Tab ─────────────────────────────────────────────────────

function StockMovementsTab({ farmId, locationId }: { farmId: number; locationId: number }) {
  const qc = useQueryClient();
  const { toast } = useToast();

  const [addOpen, setAddOpen] = useState(false);
  const [editMovement, setEditMovement] = useState<StockMovement | null>(null);
  const [movForm, setMovForm] = useState(emptyMovement());
  const [deleteMovId, setDeleteMovId] = useState<number | null>(null);
  const [filterYear, setFilterYear] = useState<string>(String(new Date().getFullYear()));
  const [linkType, setLinkType] = useState<string>("");
  const [linkId, setLinkId] = useState<number | null>(null);
  const [viewLinked, setViewLinked] = useState<{ type: string; id: number } | null>(null);

  const movQ = useQuery<{ records: StockMovement[] }>({
    queryKey: ["location-movements", farmId, locationId],
    queryFn: () => fetch(`/api/farms/${farmId}/storage-locations/${locationId}/movements`, { credentials: "include" }).then((r) => r.json()),
    enabled: !!farmId,
  });
  const movements: StockMovement[] = movQ.data?.records ?? [];

  const currentYear = String(new Date().getFullYear());
  const availableYears: string[] = Array.from(new Set(movements.map((m) => m.movementDate.slice(0, 4)))).sort((a, b) => b.localeCompare(a));
  if (!availableYears.includes(currentYear)) availableYears.unshift(currentYear);

  const visible = filterYear === "__all__" ? movements : movements.filter((m) => m.movementDate.startsWith(filterYear));
  const totalIn  = visible.filter((m) => m.direction === "in").reduce((s, m) => s + parseFloat(m.quantityTonnes || "0"), 0);
  const totalOut = visible.filter((m) => m.direction === "out").reduce((s, m) => s + parseFloat(m.quantityTonnes || "0"), 0);
  const balance  = totalIn - totalOut;

  const saveMov = useMutation({
    mutationFn: (body: Record<string, unknown>) => {
      const url = editMovement
        ? `/api/farms/${farmId}/storage-locations/${locationId}/movements/${editMovement.id}`
        : `/api/farms/${farmId}/storage-locations/${locationId}/movements`;
      return fetch(url, { method: editMovement ? "PUT" : "POST", headers: { "Content-Type": "application/json" }, credentials: "include", body: JSON.stringify(body) }).then((r) => r.json());
    },
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ["location-movements", farmId, locationId] });
      setAddOpen(false); setEditMovement(null); setMovForm(emptyMovement()); setLinkType(""); setLinkId(null);
      toast({ title: editMovement ? "Movement updated" : "Movement saved" });
    },
    onError: () => toast({ title: "Failed to save movement", variant: "destructive" }),
  });

  const deleteMov = useMutation({
    mutationFn: (id: number) => fetch(`/api/farms/${farmId}/storage-locations/${locationId}/movements/${id}`, { method: "DELETE", credentials: "include" }),
    onSuccess: () => { qc.invalidateQueries({ queryKey: ["location-movements", farmId, locationId] }); setDeleteMovId(null); toast({ title: "Movement deleted" }); },
    onError: () => toast({ title: "Delete failed", variant: "destructive" }),
  });

  const haulPickerQ = useQuery<{ records: HaulageRef[] }>({
    queryKey: ["picker-haulage", farmId],
    queryFn: () => fetch(`/api/farms/${farmId}/haulage`, { credentials: "include" }).then((r) => r.json()),
    enabled: addOpen && linkType === "haulage_record",
  });
  const salePickerQ = useQuery<{ records: GrainSaleRef[] }>({
    queryKey: ["picker-grain-sales", farmId],
    queryFn: () => fetch(`/api/farms/${farmId}/grain-sales`, { credentials: "include" }).then((r) => r.json()),
    enabled: addOpen && linkType === "grain_sale",
  });
  const harvestPickerQ = useQuery<{ records: HarvestRef[] }>({
    queryKey: ["picker-harvests", farmId],
    queryFn: () => fetch(`/api/farms/${farmId}/harvests`, { credentials: "include" }).then((r) => r.json()),
    enabled: addOpen && linkType === "harvest_record",
  });

  function openAdd() { setEditMovement(null); setMovForm(emptyMovement()); setLinkType(""); setLinkId(null); setAddOpen(true); }
  function openEdit(m: StockMovement) {
    setEditMovement(m);
    setMovForm({
      movementDate: m.movementDate, movementType: m.movementType, direction: m.direction,
      commodity: m.commodity ?? "", variety: m.variety ?? "", cropYear: m.cropYear ?? "",
      quantityTonnes: m.quantityTonnes, reference: m.reference ?? "", notes: m.notes ?? "",
    });
    setLinkType(m.linkedRecordType ?? "");
    setLinkId(m.linkedRecordId ?? null);
    setAddOpen(true);
  }

  function handleTypeChange(type: string) {
    const dir = movTypeDirection(type);
    setMovForm((f) => ({ ...f, movementType: type, direction: dir === "either" ? f.direction : dir }));
  }

  function handleSubmit() {
    saveMov.mutate({
      movementDate: movForm.movementDate,
      movementType: movForm.movementType,
      direction: movForm.direction,
      commodity: movForm.commodity || null,
      variety: movForm.variety || null,
      cropYear: movForm.cropYear || null,
      quantityTonnes: movForm.quantityTonnes,
      reference: movForm.reference || null,
      notes: movForm.notes || null,
      linkedRecordType: linkType || null,
      linkedRecordId: linkId || null,
    });
  }

  function closeDialog() { setAddOpen(false); setEditMovement(null); setMovForm(emptyMovement()); setLinkType(""); setLinkId(null); }

  return (
    <div className="space-y-3">
      {/* Header */}
      <div className="flex items-center justify-between flex-wrap gap-2">
        <div className="flex items-center gap-1.5">
          <label className="text-xs text-muted-foreground whitespace-nowrap">Year:</label>
          <select
            value={filterYear}
            onChange={(e) => setFilterYear(e.target.value)}
            className="h-8 rounded-md border border-input bg-background px-2 text-xs focus:outline-none focus:ring-1 focus:ring-ring"
          >
            {availableYears.map((y) => <option key={y} value={y}>{y}</option>)}
            <option value="__all__">All years</option>
          </select>
        </div>
        <Button size="sm" className="gap-1.5 text-xs h-8" onClick={openAdd}>
          <Plus className="h-3.5 w-3.5" /> Record Movement
        </Button>
      </div>

      {/* Balance summary */}
      {visible.length > 0 && (
        <div className="grid grid-cols-3 gap-2">
          <div className="rounded-md border bg-green-50 px-3 py-2 text-center">
            <p className="text-[10px] text-green-700 font-medium uppercase tracking-wide">Total In</p>
            <p className="text-sm font-bold text-green-800 tabular-nums">{totalIn.toFixed(2)} t</p>
          </div>
          <div className="rounded-md border bg-amber-50 px-3 py-2 text-center">
            <p className="text-[10px] text-amber-700 font-medium uppercase tracking-wide">Total Out</p>
            <p className="text-sm font-bold text-amber-800 tabular-nums">{totalOut.toFixed(2)} t</p>
          </div>
          <div className={`rounded-md border px-3 py-2 text-center ${balance >= 0 ? "bg-blue-50" : "bg-red-50"}`}>
            <p className={`text-[10px] font-medium uppercase tracking-wide ${balance >= 0 ? "text-blue-700" : "text-red-700"}`}>Balance</p>
            <p className={`text-sm font-bold tabular-nums ${balance >= 0 ? "text-blue-800" : "text-red-800"}`}>{balance.toFixed(2)} t</p>
          </div>
        </div>
      )}

      {movQ.isLoading && <p className="text-xs text-muted-foreground">Loading movements…</p>}
      {!movQ.isLoading && movements.length === 0 && (
        <div className="border rounded-lg p-8 text-center text-muted-foreground">
          <Layers className="h-8 w-8 mx-auto mb-2 opacity-30" />
          <p className="text-sm">No stock movements recorded yet.</p>
          <p className="text-xs mt-1">Use "Record Movement" to log intake, dispatch, or transfers.</p>
        </div>
      )}
      {!movQ.isLoading && movements.length > 0 && visible.length === 0 && (
        <p className="text-xs text-muted-foreground italic">No movements for {filterYear}. Select a different year or "All years".</p>
      )}

      {visible.length > 0 && (
        <div className="border rounded-lg overflow-hidden">
          <table className="w-full text-xs">
            <thead className="bg-muted/50">
              <tr>
                <th className="text-left px-3 py-2 font-medium">Date</th>
                <th className="text-left px-3 py-2 font-medium">Type</th>
                <th className="text-left px-3 py-2 font-medium hidden sm:table-cell">Commodity</th>
                <th className="text-left px-3 py-2 font-medium hidden md:table-cell">Crop Year</th>
                <th className="text-left px-3 py-2 font-medium hidden lg:table-cell">Reference</th>
                <th className="text-right px-3 py-2 font-medium">Dir</th>
                <th className="text-right px-3 py-2 font-medium">Qty (t)</th>
                <th className="px-2 py-2 w-14" />
              </tr>
            </thead>
            <tbody className="divide-y">
              {visible.map((m) => (
                <tr key={m.id} className="hover:bg-muted/30">
                  <td className="px-3 py-2 tabular-nums">{m.movementDate}</td>
                  <td className="px-3 py-2">
                    <span className="inline-flex items-center px-1.5 py-0.5 rounded-full bg-muted text-[10px] font-medium">
                      {MOVEMENT_TYPES.find((t) => t.value === m.movementType)?.label ?? m.movementType}
                    </span>
                  </td>
                  <td className="px-3 py-2 hidden sm:table-cell text-muted-foreground">{m.commodity || "—"}{m.variety ? ` — ${m.variety}` : ""}</td>
                  <td className="px-3 py-2 hidden md:table-cell text-muted-foreground">{m.cropYear || "—"}</td>
                  <td className="px-3 py-2 hidden lg:table-cell max-w-[140px]">
                    {m.linkedRecordId ? (
                      <button
                        onClick={() => setViewLinked({ type: m.linkedRecordType!, id: m.linkedRecordId! })}
                        className="group flex items-center gap-1 text-blue-600 hover:text-blue-800"
                      >
                        <span className="truncate max-w-[100px] text-xs underline underline-offset-2">{m.reference || `#${m.linkedRecordId}`}</span>
                        <Link2 className="h-3 w-3 flex-shrink-0 opacity-60 group-hover:opacity-100" />
                      </button>
                    ) : (
                      <span className="text-muted-foreground text-xs truncate">{m.reference || "—"}</span>
                    )}
                  </td>
                  <td className="px-3 py-2 text-right">
                    <span className={`inline-flex items-center px-1.5 py-0.5 rounded-full text-[10px] font-semibold ${m.direction === "in" ? "bg-green-100 text-green-800" : "bg-amber-100 text-amber-800"}`}>
                      {m.direction === "in" ? "IN" : "OUT"}
                    </span>
                  </td>
                  <td className="px-3 py-2 text-right font-medium tabular-nums">{parseFloat(m.quantityTonnes).toFixed(3)}</td>
                  <td className="px-2 py-2">
                    <div className="flex items-center gap-0.5 justify-end">
                      <button onClick={() => openEdit(m)} className="p-1 rounded hover:bg-muted/50"><Pencil className="h-3 w-3" /></button>
                      <button onClick={() => setDeleteMovId(m.id)} className="p-1 rounded hover:bg-muted/50 text-destructive"><Trash2 className="h-3 w-3" /></button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* Add / Edit Dialog */}
      <Dialog open={addOpen} onOpenChange={(o) => { if (!o) closeDialog(); else setAddOpen(true); }}>
        <DialogContent style={{ maxWidth: 520 }} aria-describedby={undefined}>
          <DialogHeader><DialogTitle>{editMovement ? "Edit Movement" : "Record Stock Movement"}</DialogTitle></DialogHeader>
          <div className="space-y-3 pt-1">
            <div className="grid grid-cols-2 gap-3">
              <div className="space-y-1">
                <Label>Date <span className="text-destructive">*</span></Label>
                <Input type="date" value={movForm.movementDate} onChange={(e) => setMovForm((f) => ({ ...f, movementDate: e.target.value }))} />
              </div>
              <div className="space-y-1">
                <Label>Movement type <span className="text-destructive">*</span></Label>
                <Select value={movForm.movementType} onValueChange={handleTypeChange}>
                  <SelectTrigger><SelectValue /></SelectTrigger>
                  <SelectContent>
                    {MOVEMENT_TYPES.map((t) => <SelectItem key={t.value} value={t.value}>{t.label}</SelectItem>)}
                  </SelectContent>
                </Select>
              </div>
            </div>

            {movTypeDirection(movForm.movementType) === "either" && (
              <div className="space-y-1">
                <Label>Direction</Label>
                <Select value={movForm.direction} onValueChange={(v) => setMovForm((f) => ({ ...f, direction: v }))}>
                  <SelectTrigger><SelectValue /></SelectTrigger>
                  <SelectContent>
                    <SelectItem value="in">In (stock increase)</SelectItem>
                    <SelectItem value="out">Out (stock decrease)</SelectItem>
                  </SelectContent>
                </Select>
              </div>
            )}

            <div className="grid grid-cols-2 gap-3">
              <div className="space-y-1">
                <Label>Commodity</Label>
                <Input list="crop-types-list" placeholder="e.g. Wheat" value={movForm.commodity} onChange={(e) => setMovForm((f) => ({ ...f, commodity: e.target.value }))} />
                <datalist id="crop-types-list">{CROP_TYPES.map((c) => <option key={c} value={c} />)}</datalist>
              </div>
              <div className="space-y-1">
                <Label>Variety</Label>
                <Input placeholder="e.g. Skyscraper" value={movForm.variety} onChange={(e) => setMovForm((f) => ({ ...f, variety: e.target.value }))} />
              </div>
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div className="space-y-1">
                <Label>Crop year</Label>
                <Input placeholder="e.g. 2024/25" value={movForm.cropYear} onChange={(e) => setMovForm((f) => ({ ...f, cropYear: e.target.value }))} />
              </div>
              <div className="space-y-1">
                <Label>Quantity (tonnes) <span className="text-destructive">*</span></Label>
                <Input type="number" step="0.001" placeholder="0.000" value={movForm.quantityTonnes} onChange={(e) => setMovForm((f) => ({ ...f, quantityTonnes: e.target.value }))} />
              </div>
            </div>

            <div className="space-y-1">
              <Label>Reference</Label>
              <Input placeholder="Haulage ticket, contract ref, etc." value={movForm.reference} onChange={(e) => setMovForm((f) => ({ ...f, reference: e.target.value }))} />
            </div>
            <div className="space-y-1">
              <Label>Notes</Label>
              <Input placeholder="Optional notes" value={movForm.notes} onChange={(e) => setMovForm((f) => ({ ...f, notes: e.target.value }))} />
            </div>

            {/* Link to record */}
            <div className="space-y-2 border-t pt-3 mt-1">
              <p className="text-xs font-medium text-muted-foreground uppercase tracking-wide">Link to existing record <span className="normal-case font-normal">(optional)</span></p>
              <div className="space-y-1">
                <Label className="text-xs">Record type</Label>
                <Select value={linkType || "__none__"} onValueChange={(v) => { setLinkType(v === "__none__" ? "" : v); setLinkId(null); }}>
                  <SelectTrigger className="h-8 text-xs"><SelectValue placeholder="— None —" /></SelectTrigger>
                  <SelectContent>
                    <SelectItem value="__none__">— None —</SelectItem>
                    <SelectItem value="haulage_record">Haulage record</SelectItem>
                    <SelectItem value="grain_sale">Grain sale</SelectItem>
                    <SelectItem value="harvest_record">Harvest record</SelectItem>
                  </SelectContent>
                </Select>
              </div>

              {linkType === "haulage_record" && (
                <div className="space-y-1">
                  <Label className="text-xs">Select haulage record</Label>
                  <Select value={linkId ? String(linkId) : "__none__"} onValueChange={(v) => {
                    if (v === "__none__") { setLinkId(null); return; }
                    const id = parseInt(v);
                    setLinkId(id);
                    const rec = (haulPickerQ.data?.records ?? []).find((r) => r.id === id);
                    if (rec) setMovForm((f) => ({ ...f, reference: rec.weighbridgeTicketNo || `HAU-${id}` }));
                  }}>
                    <SelectTrigger className="h-8 text-xs"><SelectValue placeholder="Select…" /></SelectTrigger>
                    <SelectContent>
                      <SelectItem value="__none__">— None —</SelectItem>
                      {(haulPickerQ.data?.records ?? []).map((r) => (
                        <SelectItem key={r.id} value={String(r.id)}>
                          {r.weighbridgeTicketNo || `HAU-${r.id}`}{r.commodity ? ` · ${r.commodity}` : ""}{r.weightTonnes ? ` · ${r.weightTonnes}t` : ""}{r.destination ? ` → ${r.destination}` : ""}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
              )}

              {linkType === "grain_sale" && (
                <div className="space-y-1">
                  <Label className="text-xs">Select grain sale</Label>
                  <Select value={linkId ? String(linkId) : "__none__"} onValueChange={(v) => {
                    if (v === "__none__") { setLinkId(null); return; }
                    const id = parseInt(v);
                    setLinkId(id);
                    const rec = (salePickerQ.data?.records ?? []).find((r) => r.id === id);
                    if (rec) setMovForm((f) => ({ ...f, reference: rec.merchantRef || `SALE-${id}` }));
                  }}>
                    <SelectTrigger className="h-8 text-xs"><SelectValue placeholder="Select…" /></SelectTrigger>
                    <SelectContent>
                      <SelectItem value="__none__">— None —</SelectItem>
                      {(salePickerQ.data?.records ?? []).map((r) => (
                        <SelectItem key={r.id} value={String(r.id)}>
                          {r.merchantRef || `SALE-${r.id}`} · {r.buyer} · {r.commodity} {r.tonnage}t
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
              )}

              {linkType === "harvest_record" && (
                <div className="space-y-1">
                  <Label className="text-xs">Select harvest record</Label>
                  <Select value={linkId ? String(linkId) : "__none__"} onValueChange={(v) => {
                    if (v === "__none__") { setLinkId(null); return; }
                    const id = parseInt(v);
                    setLinkId(id);
                    const rec = (harvestPickerQ.data?.records ?? []).find((r) => r.id === id);
                    if (rec) setMovForm((f) => ({ ...f, reference: `${rec.harvestDate?.slice(0, 10) ?? ""} ${rec.field?.name ?? ""} ${rec.crop?.cropType ?? ""}`.trim() }));
                  }}>
                    <SelectTrigger className="h-8 text-xs"><SelectValue placeholder="Select…" /></SelectTrigger>
                    <SelectContent>
                      <SelectItem value="__none__">— None —</SelectItem>
                      {(harvestPickerQ.data?.records ?? []).map((r) => (
                        <SelectItem key={r.id} value={String(r.id)}>
                          {r.harvestDate?.slice(0, 10) ?? "?"} · {r.field?.name ?? "?"} · {r.crop?.cropType ?? "?"}{r.yieldTonnes ? ` ${r.yieldTonnes}t` : ""}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>
              )}
            </div>
          </div>
          <DialogFooter className="pt-2">
            <Button variant="outline" onClick={closeDialog}>Cancel</Button>
            <Button disabled={!movForm.movementDate || !movForm.quantityTonnes || saveMov.isPending} onClick={handleSubmit}>
              {saveMov.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : editMovement ? "Save Changes" : "Save Movement"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* Delete confirm */}
      <Dialog open={deleteMovId !== null} onOpenChange={(o) => { if (!o) setDeleteMovId(null); }}>
        <DialogContent style={{ maxWidth: 380 }} aria-describedby={undefined}>
          <DialogHeader><DialogTitle>Delete Movement</DialogTitle></DialogHeader>
          <p className="text-sm text-muted-foreground">Are you sure? This cannot be undone.</p>
          <DialogFooter>
            <Button variant="outline" onClick={() => setDeleteMovId(null)}>Cancel</Button>
            <Button variant="destructive" disabled={deleteMov.isPending} onClick={() => deleteMovId !== null && deleteMov.mutate(deleteMovId)}>
              {deleteMov.isPending ? "Deleting…" : "Delete"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      {/* Linked record detail viewer */}
      {viewLinked && (
        <LinkedRecordDetailDialog
          farmId={farmId}
          linkedRecordType={viewLinked.type}
          linkedRecordId={viewLinked.id}
          onClose={() => setViewLinked(null)}
        />
      )}
    </div>
  );
}

// ─── Merchant Charges Panel ──────────────────────────────────────────────────

function MerchantChargesPanel({ farmId, locationId, location }: { farmId: number; locationId: number; location: StorageLocation }) {
  const qc = useQueryClient();
  const { toast } = useToast();

  const [addOpen, setAddOpen] = useState(false);
  const [editCharge, setEditCharge] = useState<MerchantCharge | null>(null);
  const [chargeForm, setChargeForm] = useState(emptyCharge());
  const [deleteChargeId, setDeleteChargeId] = useState<number | null>(null);
  const [autoGenOpen, setAutoGenOpen] = useState(false);
  const [autoGenForm, setAutoGenForm] = useState(emptyAutoGen());
  const [filterYear, setFilterYear] = useState<string>(String(new Date().getFullYear()));

  const chargesQ = useQuery<{ records: MerchantCharge[] }>({
    queryKey: ["merchant-charges", farmId, locationId],
    queryFn: () => fetch(`/api/farms/${farmId}/storage-locations/${locationId}/charges`, { credentials: "include" }).then((r) => r.json()),
    enabled: !!farmId,
  });
  const charges: MerchantCharge[] = chargesQ.data?.records ?? [];

  // Derive available years from charge dates so the dropdown only shows years that have data
  const availableYears: string[] = Array.from(
    new Set(charges.map((c) => c.chargeDate.slice(0, 4)))
  ).sort((a, b) => b.localeCompare(a));

  // Ensure the current-year default is included even when there are no charges yet
  const currentYear = String(new Date().getFullYear());
  if (!availableYears.includes(currentYear)) availableYears.unshift(currentYear);

  const visibleCharges = filterYear === "__all__" ? charges : charges.filter((c) => c.chargeDate.startsWith(filterYear));
  const totalPence = visibleCharges.reduce((s, c) => s + c.amountPence, 0);

  const saveCharge = useMutation({
    mutationFn: (body: Record<string, unknown>) => {
      const url = editCharge
        ? `/api/farms/${farmId}/storage-locations/${locationId}/charges/${editCharge.id}`
        : `/api/farms/${farmId}/storage-locations/${locationId}/charges`;
      return fetch(url, { method: editCharge ? "PUT" : "POST", headers: { "Content-Type": "application/json" }, credentials: "include", body: JSON.stringify(body) }).then((r) => r.json());
    },
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ["merchant-charges", farmId, locationId] });
      setAddOpen(false); setEditCharge(null); setChargeForm(emptyCharge());
      toast({ title: editCharge ? "Charge updated" : "Charge saved" });
    },
    onError: () => toast({ title: "Failed to save charge", variant: "destructive" }),
  });

  const deleteCharge = useMutation({
    mutationFn: (id: number) => fetch(`/api/farms/${farmId}/storage-locations/${locationId}/charges/${id}`, { method: "DELETE", credentials: "include" }),
    onSuccess: () => { qc.invalidateQueries({ queryKey: ["merchant-charges", farmId, locationId] }); setDeleteChargeId(null); toast({ title: "Charge deleted" }); },
    onError: () => toast({ title: "Delete failed", variant: "destructive" }),
  });

  const autoGenMut = useMutation({
    mutationFn: (body: Record<string, unknown>) =>
      fetch(`/api/farms/${farmId}/storage-locations/${locationId}/charges/auto-generate`, { method: "POST", headers: { "Content-Type": "application/json" }, credentials: "include", body: JSON.stringify(body) }).then((r) => r.json()),
    onSuccess: (data) => {
      qc.invalidateQueries({ queryKey: ["merchant-charges", farmId, locationId] });
      setAutoGenOpen(false); setAutoGenForm(emptyAutoGen());
      toast({ title: `${data.records?.length ?? 0} charge line(s) generated` });
    },
    onError: () => toast({ title: "Auto-generate failed", variant: "destructive" }),
  });

  function openAdd() { setEditCharge(null); setChargeForm(emptyCharge()); setAddOpen(true); }
  function openEdit(c: MerchantCharge) {
    setEditCharge(c);
    setChargeForm({
      chargeDate: c.chargeDate, chargeType: c.chargeType, description: c.description ?? "",
      quantityTonnes: c.quantityTonnes ?? "", rateUsed: c.rateUsed ?? "",
      amountPence: String(c.amountPence / 100),
      statementReference: c.statementReference ?? "", statementDate: c.statementDate ?? "", notes: c.notes ?? "",
    });
    setAddOpen(true);
  }

  const hasRates = !!(location.storageRatePptWeek || location.intakeChargePpt || location.outloadingChargePpt || location.dryingChargePpt || location.insuranceRatePptWeek);

  return (
    <td colSpan={7} className="px-0 py-0">
      <div className="bg-muted/20 border-t px-6 py-4 space-y-3">
        <div className="flex items-center justify-between flex-wrap gap-2">
          <div className="flex items-center gap-2 text-sm font-semibold text-muted-foreground">
            <Receipt className="h-4 w-4 text-amber-600" />
            Merchant Storage Charges
            {location.merchantName && <span className="font-normal text-xs">— {location.merchantName}</span>}
          </div>
          <div className="flex items-center gap-2 flex-wrap">
            {/* Year filter */}
            <div className="flex items-center gap-1.5">
              <label className="text-xs text-muted-foreground whitespace-nowrap">Year:</label>
              <select
                value={filterYear}
                onChange={(e) => setFilterYear(e.target.value)}
                className="h-8 rounded-md border border-input bg-background px-2 text-xs focus:outline-none focus:ring-1 focus:ring-ring"
              >
                {availableYears.map((y) => (
                  <option key={y} value={y}>{y}</option>
                ))}
                <option value="__all__">All years</option>
              </select>
            </div>
            {hasRates && (
              <Button size="sm" variant="outline" className="gap-1.5 text-xs h-8" onClick={() => { setAutoGenForm(emptyAutoGen()); setAutoGenOpen(true); }}>
                <Calculator className="h-3.5 w-3.5" /> Auto-generate
              </Button>
            )}
            <Button size="sm" className="gap-1.5 text-xs h-8" onClick={openAdd}>
              <Plus className="h-3.5 w-3.5" /> Manual Charge
            </Button>
          </div>
        </div>

        {chargesQ.isLoading && <p className="text-xs text-muted-foreground">Loading charges…</p>}

        {!chargesQ.isLoading && charges.length === 0 && (
          <p className="text-xs text-muted-foreground italic">No charges recorded yet.{hasRates ? " Use Auto-generate to create charges from the rate card, or add a manual charge." : " Add a manual charge or set up rate card fields in Edit Location."}</p>
        )}

        {!chargesQ.isLoading && charges.length > 0 && visibleCharges.length === 0 && (
          <p className="text-xs text-muted-foreground italic">No charges for {filterYear}. Select a different year or choose "All years".</p>
        )}

        {visibleCharges.length > 0 && (
          <div className="overflow-x-auto">
            <table className="w-full text-xs">
              <thead>
                <tr className="border-b text-muted-foreground">
                  <th className="text-left py-1.5 pr-3 font-medium">Date</th>
                  <th className="text-left py-1.5 pr-3 font-medium">Type</th>
                  <th className="text-left py-1.5 pr-3 font-medium">Description</th>
                  <th className="text-right py-1.5 pr-3 font-medium">Qty (t)</th>
                  <th className="text-right py-1.5 pr-3 font-medium">Rate</th>
                  <th className="text-right py-1.5 pr-3 font-medium">Amount</th>
                  <th className="py-1.5 w-14" />
                </tr>
              </thead>
              <tbody className="divide-y divide-muted/30">
                {visibleCharges.map((c) => (
                  <tr key={c.id} className="hover:bg-muted/20">
                    <td className="py-1.5 pr-3 tabular-nums">{c.chargeDate}</td>
                    <td className="py-1.5 pr-3">
                      <span className="inline-flex items-center gap-1 px-1.5 py-0.5 rounded-full bg-amber-100 text-amber-800 text-[10px] font-medium">
                        {CHARGE_TYPE_LABELS[c.chargeType] ?? c.chargeType}
                        {c.isAutoGenerated && <Calculator className="h-2.5 w-2.5" />}
                      </span>
                    </td>
                    <td className="py-1.5 pr-3 text-muted-foreground max-w-[200px] truncate">{c.description || "—"}</td>
                    <td className="py-1.5 pr-3 text-right tabular-nums">{c.quantityTonnes || "—"}</td>
                    <td className="py-1.5 pr-3 text-right tabular-nums">{c.rateUsed ? `£${parseFloat(c.rateUsed).toFixed(4)}` : "—"}</td>
                    <td className="py-1.5 pr-3 text-right font-medium tabular-nums">{fmtPence(c.amountPence)}</td>
                    <td className="py-1.5">
                      <div className="flex items-center gap-0.5">
                        <button onClick={() => openEdit(c)} className="p-1 rounded hover:bg-muted/50"><Pencil className="h-3 w-3" /></button>
                        <button onClick={() => setDeleteChargeId(c.id)} className="p-1 rounded hover:bg-muted/50 text-destructive"><Trash2 className="h-3 w-3" /></button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
              <tfoot>
                <tr className="border-t-2 border-amber-200">
                  <td colSpan={5} className="py-2 pr-3 text-right font-semibold text-xs">
                    {filterYear === "__all__" ? "Total (all years):" : `Total ${filterYear}:`}
                  </td>
                  <td className="py-2 pr-3 text-right font-bold text-sm text-amber-800">{fmtPence(totalPence)}</td>
                  <td />
                </tr>
              </tfoot>
            </table>
          </div>
        )}

        {/* Add / Edit Charge Dialog */}
        <Dialog open={addOpen} onOpenChange={(o) => { setAddOpen(o); if (!o) { setEditCharge(null); setChargeForm(emptyCharge()); } }}>
          <DialogContent style={{ maxWidth: 520 }} aria-describedby={undefined}>
            <DialogHeader><DialogTitle>{editCharge ? "Edit Charge" : "Add Manual Charge"}</DialogTitle></DialogHeader>
            <div className="space-y-3 pt-1">
              <div className="grid grid-cols-2 gap-3">
                <div className="space-y-1">
                  <Label>Date <span className="text-destructive">*</span></Label>
                  <Input type="date" value={chargeForm.chargeDate} onChange={(e) => setChargeForm((f) => ({ ...f, chargeDate: e.target.value }))} />
                </div>
                <div className="space-y-1">
                  <Label>Charge type</Label>
                  <Select value={chargeForm.chargeType} onValueChange={(v) => setChargeForm((f) => ({ ...f, chargeType: v }))}>
                    <SelectTrigger><SelectValue /></SelectTrigger>
                    <SelectContent>
                      {Object.entries(CHARGE_TYPE_LABELS).map(([v, l]) => <SelectItem key={v} value={v}>{l}</SelectItem>)}
                    </SelectContent>
                  </Select>
                </div>
              </div>
              <div className="space-y-1">
                <Label>Description</Label>
                <Input placeholder="e.g. Storage Oct–Nov 2024" value={chargeForm.description} onChange={(e) => setChargeForm((f) => ({ ...f, description: e.target.value }))} />
              </div>
              <div className="grid grid-cols-3 gap-3">
                <div className="space-y-1">
                  <Label>Qty (tonnes)</Label>
                  <Input type="number" step="0.01" placeholder="250" value={chargeForm.quantityTonnes} onChange={(e) => setChargeForm((f) => ({ ...f, quantityTonnes: e.target.value }))} />
                </div>
                <div className="space-y-1">
                  <Label>Rate (£/t)</Label>
                  <Input type="number" step="0.0001" placeholder="0.50" value={chargeForm.rateUsed} onChange={(e) => setChargeForm((f) => ({ ...f, rateUsed: e.target.value }))} />
                </div>
                <div className="space-y-1">
                  <Label>Amount (£) <span className="text-destructive">*</span></Label>
                  <Input type="number" step="0.01" placeholder="125.00" value={chargeForm.amountPence} onChange={(e) => setChargeForm((f) => ({ ...f, amountPence: e.target.value }))} />
                </div>
              </div>
              <div className="grid grid-cols-2 gap-3">
                <div className="space-y-1">
                  <Label>Statement ref</Label>
                  <Input placeholder="INV-2024-001" value={chargeForm.statementReference} onChange={(e) => setChargeForm((f) => ({ ...f, statementReference: e.target.value }))} />
                </div>
                <div className="space-y-1">
                  <Label>Statement date</Label>
                  <Input type="date" value={chargeForm.statementDate} onChange={(e) => setChargeForm((f) => ({ ...f, statementDate: e.target.value }))} />
                </div>
              </div>
              <div className="space-y-1">
                <Label>Notes</Label>
                <Input placeholder="Any additional notes" value={chargeForm.notes} onChange={(e) => setChargeForm((f) => ({ ...f, notes: e.target.value }))} />
              </div>
            </div>
            <DialogFooter>
              <Button variant="outline" onClick={() => setAddOpen(false)}>Cancel</Button>
              <Button
                disabled={saveCharge.isPending || !chargeForm.chargeDate || !chargeForm.amountPence}
                onClick={() => saveCharge.mutate({
                  chargeDate: chargeForm.chargeDate,
                  chargeType: chargeForm.chargeType,
                  description: chargeForm.description || null,
                  quantityTonnes: chargeForm.quantityTonnes || null,
                  rateUsed: chargeForm.rateUsed || null,
                  amountPence: Math.round(parseFloat(chargeForm.amountPence || "0") * 100),
                  statementReference: chargeForm.statementReference || null,
                  statementDate: chargeForm.statementDate || null,
                  notes: chargeForm.notes || null,
                })}
              >
                {saveCharge.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : editCharge ? "Save Changes" : "Add Charge"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Auto-generate Dialog */}
        <Dialog open={autoGenOpen} onOpenChange={(o) => { setAutoGenOpen(o); if (!o) setAutoGenForm(emptyAutoGen()); }}>
          <DialogContent style={{ maxWidth: 480 }} aria-describedby={undefined}>
            <DialogHeader>
              <DialogTitle className="flex items-center gap-2"><Calculator className="h-4 w-4 text-amber-600" /> Auto-generate Charges</DialogTitle>
            </DialogHeader>
            <p className="text-xs text-muted-foreground">Generate charge lines from the rate card configured for this location.</p>
            <div className="space-y-3 pt-1">
              <div className="grid grid-cols-2 gap-3">
                <div className="space-y-1">
                  <Label>Period start <span className="text-destructive">*</span></Label>
                  <Input type="date" value={autoGenForm.periodStart} onChange={(e) => setAutoGenForm((f) => ({ ...f, periodStart: e.target.value }))} />
                </div>
                <div className="space-y-1">
                  <Label>Period end <span className="text-destructive">*</span></Label>
                  <Input type="date" value={autoGenForm.periodEnd} onChange={(e) => setAutoGenForm((f) => ({ ...f, periodEnd: e.target.value }))} />
                </div>
              </div>
              <div className="space-y-1">
                <Label>Quantity (tonnes) <span className="text-destructive">*</span></Label>
                <Input type="number" step="0.01" placeholder="e.g. 250" value={autoGenForm.quantityTonnes} onChange={(e) => setAutoGenForm((f) => ({ ...f, quantityTonnes: e.target.value }))} />
              </div>
              <div className="space-y-1.5">
                <Label>Charge types to include</Label>
                <div className="flex flex-wrap gap-2">
                  {(["storage", "intake", "outloading", "drying", "insurance"] as const).map((ct) => {
                    const rateKey = ct === "storage" ? "storageRatePptWeek" : ct === "intake" ? "intakeChargePpt" : ct === "outloading" ? "outloadingChargePpt" : ct === "drying" ? "dryingChargePpt" : "insuranceRatePptWeek";
                    const hasRate = !!(location[rateKey as keyof StorageLocation]);
                    return (
                      <label key={ct} className={`flex items-center gap-1.5 text-xs px-2.5 py-1.5 rounded-full border cursor-pointer transition-colors ${autoGenForm.chargeTypes.includes(ct) ? "bg-amber-100 border-amber-400 text-amber-800" : "bg-muted/30 text-muted-foreground"} ${!hasRate ? "opacity-40" : ""}`}>
                        <input type="checkbox" className="sr-only" checked={autoGenForm.chargeTypes.includes(ct)} disabled={!hasRate}
                          onChange={(e) => setAutoGenForm((f) => ({ ...f, chargeTypes: e.target.checked ? [...f.chargeTypes, ct] : f.chargeTypes.filter((x) => x !== ct) }))} />
                        {CHARGE_TYPE_LABELS[ct]}
                        {hasRate && location[rateKey as keyof StorageLocation] && <span className="font-mono opacity-60">£{parseFloat(location[rateKey as keyof StorageLocation] as string).toFixed(4)}</span>}
                        {!hasRate && <span className="opacity-60">no rate</span>}
                      </label>
                    );
                  })}
                </div>
              </div>
            </div>
            <DialogFooter>
              <Button variant="outline" onClick={() => setAutoGenOpen(false)}>Cancel</Button>
              <Button
                disabled={autoGenMut.isPending || !autoGenForm.periodStart || !autoGenForm.periodEnd || !autoGenForm.quantityTonnes || autoGenForm.chargeTypes.length === 0}
                onClick={() => autoGenMut.mutate({ periodStart: autoGenForm.periodStart, periodEnd: autoGenForm.periodEnd, quantityTonnes: parseFloat(autoGenForm.quantityTonnes), chargeTypes: autoGenForm.chargeTypes })}
              >
                {autoGenMut.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : "Generate Charges"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Delete Charge Dialog */}
        <Dialog open={deleteChargeId !== null} onOpenChange={(o) => { if (!o) setDeleteChargeId(null); }}>
          <DialogContent style={{ maxWidth: 360 }} aria-describedby={undefined}>
            <DialogHeader><DialogTitle>Delete Charge</DialogTitle></DialogHeader>
            <p className="text-sm text-muted-foreground">Are you sure? This cannot be undone.</p>
            <DialogFooter>
              <Button variant="outline" onClick={() => setDeleteChargeId(null)}>Cancel</Button>
              <Button variant="destructive" disabled={deleteCharge.isPending} onClick={() => deleteChargeId !== null && deleteCharge.mutate(deleteChargeId)}>
                {deleteCharge.isPending ? "Deleting…" : "Delete"}
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </div>
    </td>
  );
}

